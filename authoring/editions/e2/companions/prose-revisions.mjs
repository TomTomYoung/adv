export function reviseArcs(drafts){
 const arcs=structuredClone(drafts);
 for(const [number,before,after,reason] of revisions){
  const q=Object.values(arcs).flat().find(q=>q.number===number);let matches=0;
  const replace=value=>{
   if(typeof value==='string'){if(value.includes(before)){matches++;return value.replace(before,after);}return value;}
   if(Array.isArray(value))return value.map(replace);
   if(value&&typeof value==='object')return Object.fromEntries(Object.entries(value).map(([k,v])=>[k,replace(v)]));
   return value;
  };
  const revised=replace(q);if(matches!==1)throw Error(`q${number}: 推敲対象は1箇所必要 (${matches})`);
  Object.assign(q,revised);
 }
 for(const q of Object.values(arcs).flat())q.review={scope:['entry','survey',...q.choices.flatMap(c=>[`result_${c.id}`,`home_${c.id}`])],changes:revisions.filter(r=>r[0]===q.number).map(([,before,after,reason])=>({before,after,reason})),method:'作者による全分岐の読み順・主体・時点・根拠・選択前情報の点検。実読者の試読ではない。'};
 return arcs;
}
